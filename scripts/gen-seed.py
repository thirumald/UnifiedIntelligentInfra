#!/usr/bin/env python3
"""Generates apps/migrator/sql/postgis/090_seed_demo.sql — deterministic demo campus."""
import math, uuid, random, json
random.seed(42)
NS = uuid.UUID('6f1c1f5e-3b7a-4d0e-9b1c-2a5d7e9f0a11')
U = lambda k: str(uuid.uuid5(NS, k))
CH = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz_$'
G = lambda k: ''.join(random.Random(k).choice(CH[1:]) if i == 0 else random.Random(k + str(i)).choice(CH) for i in range(22))
LON0, LAT0 = 54.3773, 24.4539
def ll(x, y):
    return (LON0 + x / (111320 * math.cos(math.radians(LAT0))), LAT0 + y / 110540)

model = U('model:hq')
rows = []  # (key, ext, name, type, domain, x, y, z, storey, inBim, profile, attrs, tags, mapping)
rows.append(('bldg', 'BLDG-HQ', 'Campus HQ Building', 'building', 'facility', 0, 0, 0, None, False, None, {'floors': 3, 'gfa_m2': 8000}, ['hq'], None))
for i in range(4):
    rows.append((f'crac{i}', f'HVAC-{i+1:02d}', f'CRAC Unit {i+1} (Data Hall)', 'hvac_unit', 'facility', -32, -12 + i * 8, 4.5, 'Level 1', True, 'hvac', {'vendor': 'Vertiv', 'model': 'Liebert PDX', 'capacity_kw': 45}, ['data-hall', 'cooling'], None))
for i in range(2):
    rows.append((f'ahu{i}', f'HVAC-{i+5:02d}', f'Rooftop AHU {i+1}', 'hvac_unit', 'facility', -15 + i * 30, 12, 9.0, 'Roof', True, 'hvac_bacnet', {'vendor': 'Trane', 'protocol': 'BACnet/IP', 'device_instance': 2001 + i}, ['rooftop', 'bacnet'], 'bacnet-ahu-v1'))
for r in range(2):
    for c in range(4):
        n = r * 4 + c + 1
        rows.append((f'rack{n}', f'RACK-{n:02d}', f'Server Rack {chr(65+r)}{c+1}', 'server_rack', 'it', -18 + c * 7, 2 + r * 6, 4.5, 'Level 1', True, 'rack', {'u_height': 42, 'design_kw': 8}, ['data-hall'], None))
for i in range(4):
    rows.append((f'pdu{i}', f'PDU-{i+1:02d}', f'Row PDU {i+1}', 'pdu', 'it', 12, -2 + i * 4, 4.5, 'Level 1', True, 'pdu', {'phases': 3, 'rated_a': 32}, ['data-hall', 'power'], None))
for i in range(2):
    rows.append((f'ups{i}', f'UPS-{i+1:02d}', f'UPS {i+1}', 'ups', 'it', 26, -16 + i * 6, 0, 'Ground', True, 'ups', {'kva': 200}, ['power'], None))
rows.append(('sw', 'SW-CORE-01', 'Core Switch 01', 'network_switch', 'it', 18, 10, 4.5, 'Level 1', True, 'switch', {'vendor': 'Cisco', 'ports': 48}, ['network'], None))
rows.append(('env1', 'ENV-01', 'Data Hall Env Sensor', 'sensor', 'facility', 0, -10, 4.5, 'Level 1', True, 'env', {'measures': ['temperature', 'humidity']}, ['data-hall'], None))
cams = [(-48, 32), (48, 32), (48, -32), (-48, -32), (0, -45), (75, 20)]
for i, (x, y) in enumerate(cams):
    rows.append((f'cam{i}', f'CAM-{i+1:02d}', f'Perimeter Camera {i+1}', 'cctv_camera', 'safety', x, y, 6, None, False, 'cctv', {'resolution': '4MP', 'analytics': ['intrusion', 'loitering']}, ['perimeter'], None))
for i in range(10):
    rows.append((f'sl{i}', f'SL-{i+1:02d}', f'Streetlight {i+1}', 'streetlight', 'mobility', -90 + i * 20, -62, 0, None, False, 'streetlight', {'lamp': 'LED 120W'}, ['road'], None))
rows.append(('plc', 'PLC-PS-01', 'Pump Station PLC', 'plc', 'ot', 115, 45, 0, None, False, 'plc', {'protocol': 'Modbus/TCP', 'vendor': 'Siemens S7-1500'}, ['water', 'scada'], 'modbus-pump-v1'))
rows.append(('rtu', 'RTU-RES-01', 'Reservoir SCADA RTU', 'scada_rtu', 'ot', 140, 70, 0, None, False, 'rtu', {'protocol': 'DNP3'}, ['water', 'scada'], None))
rows.append(('sig', 'TS-01', 'Main Gate Traffic Signal', 'traffic_signal', 'mobility', 100, -62, 0, None, False, 'signal', {'phases': 4}, ['road'], None))

def q(s): return "'" + str(s).replace("'", "''") + "'"
out = ["-- migrate:seed", "-- Demo campus (Abu Dhabi) — generated by scripts/gen-seed.py; safe to re-run.", ""]
out.append(f"""INSERT INTO bim_models (id, tenant_id, name, origin, origin_alt_m, rotation_deg, width_m, depth_m, storeys, status)
VALUES ({q(model)}, 'default', 'Campus HQ Building', ST_SetSRID(ST_MakePoint({LON0}, {LAT0}), 4326), 5, 0, 80, 50,
  '{json.dumps([{"name":"Ground","elevation_m":0,"height_m":4.5},{"name":"Level 1","elevation_m":4.5,"height_m":4.5},{"name":"Roof","elevation_m":9,"height_m":1}])}'::jsonb, 'schematic')
ON CONFLICT (id) DO NOTHING;
""")
out.append("""INSERT INTO device_schema_mappings (id, tenant_id, name, protocol, mapping) VALUES
  (%s, 'default', 'bacnet-ahu-v1', 'bacnet', '%s'::jsonb),
  (%s, 'default', 'modbus-pump-v1', 'modbus', '%s'::jsonb)
ON CONFLICT (tenant_id, name) DO NOTHING;
""" % (q(U('map:bacnet')), json.dumps({"timestampPath": "timestamp", "timestampUnit": "s", "fields": [
    {"path": "objects.ZN-T.presentValue", "metric": "temperature_c", "unit": "C", "scale": 0.1},
    {"path": "objects.SA-T.presentValue", "metric": "supply_air_temp_c", "unit": "C", "scale": 0.1},
    {"path": "objects.FAN-SPD.presentValue", "metric": "fan_speed_pct", "unit": "%"},
    {"path": "objects.ALM.presentValue", "metric": "alarm", "type": "boolean"}]}),
   q(U('map:modbus')), json.dumps({"timestampPath": "t", "timestampUnit": "ms", "fields": [
    {"path": "registers.40001", "metric": "pressure_bar", "unit": "bar", "scale": 0.01},
    {"path": "registers.40002", "metric": "flow_m3h", "unit": "m3/h", "scale": 0.1},
    {"path": "registers.40003", "metric": "pump_running", "type": "boolean"}]})))
parent = U('asset:bldg')
for (k, ext, name, typ, dom, x, y, z, storey, inbim, prof, attrs, tags, mapping) in rows:
    lon, lat = ll(x, y)
    aid = U('asset:' + k)
    par = 'NULL' if k == 'bldg' or not inbim else q(parent)
    bim = f"{q(model)}, {q(G(k))}, {q('IfcUnitaryEquipment' if typ=='hvac_unit' else 'IfcFlowTerminal' if typ in ('pdu','ups') else 'IfcSensor' if typ=='sensor' else 'IfcFurnishingElement' if typ=='server_rack' else 'IfcCommunicationsAppliance')}, {x}, {y}, {z}, {q(storey)}" if inbim else "NULL, NULL, NULL, NULL, NULL, NULL, NULL"
    tg = "ARRAY[" + ",".join(q(t) for t in tags) + "]::text[]"
    out.append(f"""INSERT INTO assets (id, tenant_id, external_id, name, type, domain, status, parent_id, location, altitude_m,
  bim_model_id, ifc_guid, ifc_class, local_x, local_y, local_z, storey, attributes, tags)
VALUES ({q(aid)}, 'default', {q(ext)}, {q(name)}, {q(typ)}, {q(dom)}, 'active', {par}, ST_SetSRID(ST_MakePoint({lon:.7f}, {lat:.7f}), 4326), {z},
  {bim}, {q(json.dumps(attrs))}::jsonb, {tg})
ON CONFLICT (id) DO NOTHING;""")
    if prof:
        mp = 'NULL' if not mapping else f"(SELECT id FROM device_schema_mappings WHERE tenant_id='default' AND name={q(mapping)})"
        proto = 'mqtt-' + ('bacnet' if mapping and 'bacnet' in mapping else 'modbus' if mapping else 'json')
        out.append(f"""INSERT INTO devices (tenant_id, id, asset_id, protocol, schema_mapping_id, profile)
VALUES ('default', {q(ext.lower())}, {q(aid)}, {q(proto)}, {mp}, {q(prof)}) ON CONFLICT DO NOTHING;""")
out.append("""
-- Type-level alert thresholds (asset-level rules override these)
INSERT INTO alert_rules (tenant_id, asset_type, metric, warn_min, warn_max, crit_min, crit_max) VALUES
  ('default', 'hvac_unit',   'temperature_c',      16,   27,   12,   30),
  ('default', 'server_rack', 'inlet_temp_c',       18,   27,   15,   32),
  ('default', 'server_rack', 'power_kw',           NULL, 7.5,  NULL, 9),
  ('default', 'pdu',         'current_a',          NULL, 26,   NULL, 30),
  ('default', 'ups',         'battery_pct',        40,   NULL, 20,   NULL),
  ('default', 'ups',         'load_pct',           NULL, 80,   NULL, 95),
  ('default', 'sensor',      'humidity_pct',       30,   60,   20,   70),
  ('default', 'plc',         'pressure_bar',       2.0,  6.0,  1.2,  7.0),
  ('default', 'scada_rtu',   'reservoir_level_pct',25,   95,   10,   98),
  ('default', 'streetlight', 'power_w',            NULL, 140,  NULL, 170),
  ('default', 'network_switch','cpu_pct',          NULL, 80,   NULL, 95)
ON CONFLICT DO NOTHING;
""")
open('apps/migrator/sql/postgis/090_seed_demo.sql', 'w').write("\n".join(out) + "\n")
print(len(rows), 'assets')
